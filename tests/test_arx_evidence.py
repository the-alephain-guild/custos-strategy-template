# The receipt must agree with itself


def _resign(receipt: dict) -> None:
    """Recompute the receipt's own digests, as a forger would."""
    receipt["artifact_ref_digest"] = sha(canonical(receipt["artifact_ref"]))
    receipt["release_descriptor_matrix_digest"] = sha(
        canonical(receipt["release_descriptor_matrix"])
    )
    receipt["attestation_descriptor_matrix_digest"] = sha(
        canonical(receipt["attestation_descriptor_matrix"])
    )


@pytest.mark.parametrize(
    ("change", "complaint"),
    [
        (lambda r: r.update(release_descriptor_matrix_digest="0" * 64), "matrix"),
        (lambda r: r.update(attestation_descriptor_matrix_digest="0" * 64), "matrix"),
        (lambda r: r.update(artifact_ref_digest="0" * 64), "artifact_ref"),
        (lambda r: r["artifact_ref"].update(manifest_digest=f"sha256:{'1' * 64}"), "artifact_ref"),
        (lambda r: r.update(schema_version="something.else.v2"), "schema"),
        (lambda r: r.update(tag_is_authority=True), "tag"),
        (lambda r: r.update(referrer_verified=False), "verified"),
        (lambda r: r.update(repository="docker.io/someone/strategies"), "ghcr.io"),
        (lambda r: r.update(release_manifest_digest="sha256:short"), "digest"),
        (lambda r: r.update(discovery_tag="trend-my_idea-0.3.0"), "0.2.0"),
        (lambda r: r.pop("workflow"), "workflow"),
        (lambda r: r.update(extra=1), "extra"),
    ],
)
def test_a_receipt_that_disagrees_with_itself_is_refused(
    release, tmp_path, change, complaint
) -> None:
    receipt = copy.deepcopy(release.receipt)
    change(receipt)

    with pytest.raises(ArxError, match=complaint):
        _read(release, tmp_path, receipt)


