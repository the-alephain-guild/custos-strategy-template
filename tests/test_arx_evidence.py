    receipt = copy.deepcopy(release.receipt)
    receipt["attestation_descriptor_matrix"] = release.attestation_matrix
    receipt["attestation_manifest_digest"] = release.attestation_digest
    receipt["attestation_manifest_size_bytes"] = len(release.manifests[release.attestation_digest])
    _resign(receipt)

    with pytest.raises(ArxError, match="statement"):
        _read(release, tmp_path, receipt)


