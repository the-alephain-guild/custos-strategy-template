# Reading from GHCR


class FakeGhcr:
    """GHCR's token exchange and its /v2 reads, over the transport interface."""

    def __init__(self, release: Release, *, token_status: int = 200) -> None:
        self.release = release
        self.token_status = token_status
        self.calls: list[tuple[str, str, dict]] = []

    def __call__(self, method: str, url: str, headers, body) -> Response:
        self.calls.append((method, url, dict(headers)))
        parts = parse.urlsplit(url)
        if parts.path == "/token":
            if self.token_status != 200:
                return Response(self.token_status, [], b'{"errors":[{"code":"DENIED"}]}')
            return Response(200, [], json.dumps({"token": "registry-bearer"}).encode())
        if headers.get("Authorization") != "Bearer registry-bearer":
            return Response(401, [], b"")
        name, kind, digest = parts.path.removeprefix("/v2/").rsplit("/", 2)
        if name != REPOSITORY.removeprefix("ghcr.io/"):
            return Response(404, [], b"")
        store = self.release.manifests if kind == "manifests" else self.release.blobs
        if digest not in store:
            return Response(404, [], b"")
        return Response(200, [("Docker-Content-Digest", digest)], store[digest])


def test_ghcr_is_asked_for_pull_on_the_one_repository_only(release, tmp_path) -> None:
    path = release.save(tmp_path)
    ghcr = FakeGhcr(release)
    reader = evidence.GhcrReader(REPOSITORY, "person", "gho_secret", transport=ghcr)

    evidence.read_release(evidence.load_receipt(path), reader, receipt_path=path)

    exchanges = [call for call in ghcr.calls if parse.urlsplit(call[1]).path == "/token"]
    assert len(exchanges) == 1
    query = parse.parse_qs(parse.urlsplit(exchanges[0][1]).query)
    assert query == {
        "scope": ["repository:fork-owner/strategies/strategy-releases:pull"],
        "service": ["ghcr.io"],
    }
    assert exchanges[0][2]["Authorization"].startswith("Basic ")
    for method, url, headers in ghcr.calls:
        assert method == "GET"
        assert "gho_secret" not in url
        if parse.urlsplit(url).path != "/token":
            assert headers["Authorization"] == "Bearer registry-bearer"


