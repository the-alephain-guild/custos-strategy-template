def test_an_attestation_ref_for_another_statement_is_refused(release, tmp_path) -> None:
    digest = next(
        i["digest"] for i in release.attestation_matrix if i["role"] == "artifact_attestation_ref"
    )
    document = json.loads(release.blobs[digest])
    document["statement_sha256"] = "3" * 64
    content = canonical(document)
    del release.blobs[digest]
