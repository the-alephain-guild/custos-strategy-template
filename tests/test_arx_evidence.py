# GitHub credentials


class FakeGhCli:
    def __init__(self, scopes: str | None, logged_in: bool = True) -> None:
        self.scopes = scopes
        self.logged_in = logged_in
        self.calls: list[list[str]] = []

    def __call__(self, command: Sequence[str]) -> subprocess.CompletedProcess[str]:
        command = list(command)
        self.calls.append(command)
        if not self.logged_in:
            return subprocess.CompletedProcess(command, 1, "", "not logged in")
        if command[1:3] == ["auth", "status"]:
            lines = ["github.com", "  ✓ Logged in to github.com account person (keyring)"]
            if self.scopes is not None:
                lines.append(f"  - Token scopes: {self.scopes}")
            return subprocess.CompletedProcess(command, 0, "\n".join(lines), "")
        if command[1:3] == ["auth", "token"]:
            return subprocess.CompletedProcess(command, 0, "gho_secret\n", "")
        if command[1:3] == ["api", "user"]:
            return subprocess.CompletedProcess(command, 0, "person\n", "")
        return subprocess.CompletedProcess(command, 1, "", "unexpected")


