REPOSITORY = "ghcr.io/fork-owner/strategies/strategy-releases"
OCI_MANIFEST = "application/vnd.oci.image.manifest.v1+json"
ROLE = "dev.alephain.layer.role"
TITLE = "org.opencontainers.image.title"
MEDIA = {
    "release_config": "application/vnd.alephain.strategy-release.config.v1+json",
    "strategy_artifact": "application/vnd.alephain.strategy-wheel.v1+zip",
    "strategy_manifest": "application/vnd.alephain.strategy-manifest.v1+json",
    "strategy_artifact_ref": "application/vnd.alephain.strategy-artifact-ref.v1+json",
    "strategy_release_bom": "application/vnd.alephain.strategy-release-bom.v1+json",
    "strategy_sbom": "application/spdx+json",
    "strategy_release_statement": "application/vnd.in-toto+json",
    "attestation_config": "application/vnd.alephain.strategy-release.attestation.config.v1+json",
    "attestation_bundle": "application/vnd.dev.sigstore.bundle.v0.3+json",
    "artifact_attestation_ref": "application/vnd.alephain.artifact-attestation-ref.v1+json",
}


def canonical(value: object) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def sha(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def entry(role: str, name: str, content: bytes) -> dict:
    return {
        "digest": f"sha256:{sha(content)}",
        "media_type": MEDIA[role],
        "name": name,
        "role": role,
        "size_bytes": len(content),
    }


def manifest_descriptor(item: dict, annotated: bool) -> dict:
    value = {"digest": item["digest"], "mediaType": item["media_type"], "size": item["size_bytes"]}
    if annotated:
        value["annotations"] = {ROLE: item["role"], TITLE: item["name"]}
    return value


class Release:
    """One published release: its blobs and manifests by digest, and its receipt."""

    def __init__(self) -> None:
        self.manifests: dict[str, bytes] = {}
        self.blobs: dict[str, bytes] = {}
        statement = canonical(
            {
                "_type": "https://in-toto.io/Statement/v1",
                "subject": [{"name": "strategy.whl", "digest": {"sha256": "ab" * 32}}],
                "predicateType": "https://example.com/strategy-release/v1",
                "predicate": {"version": "0.2.0"},
            }
        )
        bundle = canonical({"mediaType": MEDIA["attestation_bundle"], "signature": "c2ln"})
        layers = [
            ("release_config", "strategy-release-oci-config-v1.json", canonical({"k": "v"})),
            ("strategy_artifact", "strategy.whl", b"PK\x03\x04 wheel bytes"),
            (
                "strategy_manifest",
                "strategy-manifest.json",
                canonical(
                    {
                        "name": "trend/my_idea",
                        "trading_scope": {
                            "connector": "binance",
                            "pairs": ["BTC-USDT"],
                            "leverage": 1,
                        },
                        "note": "ünïcode stays as written",
                    }
                ),
            ),
            ("strategy_artifact_ref", "strategy-artifact-ref.json", canonical({"ref": "wheel"})),
            ("strategy_release_bom", "strategy-release-bom.json", canonical({"bom": 1})),
            ("strategy_sbom", "strategy.spdx.json", canonical({"spdxVersion": "SPDX-2.3"})),
            ("strategy_release_statement", "strategy-release-statement.json", statement),
        ]
        release_matrix = [entry(role, name, content) for role, name, content in layers]
        for (_, _, content), item in zip(layers, release_matrix, strict=True):
            self.blobs[item["digest"]] = content
        release_manifest = canonical(
            {
                "artifactType": "application/vnd.alephain.strategy-release.v1",
                "config": manifest_descriptor(release_matrix[0], annotated=False),
                "layers": [
                    manifest_descriptor(item, annotated=True) for item in release_matrix[1:]
                ],
                "mediaType": OCI_MANIFEST,
                "schemaVersion": 2,
            }
        )
        release_digest = f"sha256:{sha(release_manifest)}"
        self.manifests[release_digest] = release_manifest
        attestation_ref = canonical(
            {
                "bundle_coordinate": f"{REPOSITORY}@sha256:{sha(bundle)}",
                "bundle_sha256": sha(bundle),
                "payload_type": "application/vnd.in-toto+json",
                "predicate_type": "https://example.com/strategy-release/v1",
                "schema_version": "alephain.artifact-attestation-ref.v1",
                "statement_coordinate": f"{REPOSITORY}@sha256:{sha(statement)}",
                "statement_sha256": sha(statement),
            }
        )
        attestation_layers = [
            ("attestation_config", "attestation-config.json", canonical({"a": 1})),
            ("attestation_bundle", "strategy-release.sigstore.json", bundle),
            ("artifact_attestation_ref", "artifact-attestation-ref.json", attestation_ref),
        ]
        attestation_matrix = [entry(r, n, c) for r, n, c in attestation_layers]
        for (_, _, content), item in zip(attestation_layers, attestation_matrix, strict=True):
            self.blobs[item["digest"]] = content
        self.subject = {
            "digest": release_digest,
            "mediaType": OCI_MANIFEST,
            "size": len(release_manifest),
        }
        self.attestation_matrix = attestation_matrix
        self._write_attestation_manifest()
        artifact_ref = {
            "artifact_kind": "oci",
            "artifact_type": "application/vnd.alephain.strategy-release.v1",
            "config": {k: release_matrix[0][k] for k in ("digest", "media_type", "size_bytes")},
            "layers": release_matrix[1:],
            "manifest_digest": release_digest,
            "registry": "ghcr.io",
            "repository": REPOSITORY.removeprefix("ghcr.io/"),
            "schema_version": 1,
        }
        self.receipt = {
            "artifact_ref": artifact_ref,
            "artifact_ref_digest": sha(canonical(artifact_ref)),
            "attestation_descriptor_matrix": attestation_matrix,
            "attestation_descriptor_matrix_digest": sha(canonical(attestation_matrix)),
            "attestation_manifest_digest": self.attestation_digest,
            "attestation_manifest_size_bytes": len(self.manifests[self.attestation_digest]),
            "blob_readback_verified": True,
            "discovery_tag": "trend-my_idea-0.2.0",
            "external_publication_completed": False,
            "manifest_readback_verified": True,
            "producer_commit": "a" * 40,
            "producer_repository": "fork-owner/strategies",
            "publisher_profile": "github_oidc",
            "referrer_verified": True,
            "release_descriptor_matrix": release_matrix,
            "release_descriptor_matrix_digest": sha(canonical(release_matrix)),
            "release_manifest_digest": release_digest,
            "release_manifest_size_bytes": len(release_manifest),
            "repository": REPOSITORY,
            "schema_version": "alephain.strategy-artifact-oci-publication-receipt.v1",
            "strategy_coordinate": "trend/my_idea",
            "tag_is_authority": False,
            "workflow": {"workflow_ref": "o/r/.github/workflows/w.yml@refs/tags/v1"},
        }

    def _write_attestation_manifest(self) -> None:
        matrix = self.attestation_matrix
        content = canonical(
            {
                "artifactType": "application/vnd.alephain.strategy-release.attestation.v1",
                "config": manifest_descriptor(matrix[0], annotated=False),
                "layers": [manifest_descriptor(item, annotated=True) for item in matrix[1:]],
                "mediaType": OCI_MANIFEST,
                "schemaVersion": 2,
                "subject": self.subject,
            }
        )
        self.attestation_digest = f"sha256:{sha(content)}"
        self.manifests[self.attestation_digest] = content

    def layer(self, role: str) -> bytes:
        matrix = self.receipt["release_descriptor_matrix"] + self.attestation_matrix
        return self.blobs[next(item["digest"] for item in matrix if item["role"] == role)]

    def save(self, root: Path, version: str = "0.2.0") -> Path:
        run = root / ".releases" / "trend" / "my_idea" / version / "strategy-release-receipt-7-1"
        run.mkdir(parents=True, exist_ok=True)
        path = run / evidence.RECEIPT_FILE
        path.write_bytes(canonical(self.receipt))
        return path


class FakeRegistry:
    """Serves what a Release published, by digest; records what it was asked."""

    def __init__(self, release: Release) -> None:
        self.release = release
        self.asked: list[str] = []

    def manifest(self, digest: str) -> bytes:
        self.asked.append(digest)
        return self.release.manifests[digest]

    def blob(self, digest: str) -> bytes:
        self.asked.append(digest)
        return self.release.blobs[digest]


@pytest.fixture
def release() -> Release:
    return Release()


RELEASE_ID = "8b2e4c1a-5d3f-4e7a-9c06-1f2a3b4c5d6e"


def _read(release: Release, tmp_path: Path, receipt: dict | None = None):
    if receipt is not None:
        release.receipt = receipt
    path = release.save(tmp_path)
    return evidence.read_release(
        evidence.load_receipt(path, version="0.2.0"), FakeRegistry(release), receipt_path=path
    )


# What ARX gets


def test_a_published_release_becomes_the_evidence_arx_drafts_from(release, tmp_path) -> None:
    found = _read(release, tmp_path)
    drafted = found.artifact_evidence(RELEASE_ID)

    assert len(drafted) == 15
    assert drafted["strategy_release_id"] == RELEASE_ID
    manifest = release.layer("strategy_manifest")
    assert drafted["manifest_canonical_json"] == manifest.decode("utf-8")
    assert drafted["manifest"] == json.loads(manifest)
    assert drafted["manifest_digest"] == sha(manifest)
    for field, role in (
        ("artifact_ref", "strategy_artifact_ref"),
        ("release_bom", "strategy_release_bom"),
        ("release_statement", "strategy_release_statement"),
        ("detached_attestation_ref", "artifact_attestation_ref"),
    ):
        content = release.layer(role)
        assert drafted[f"{field}_canonical_json"] == content.decode("utf-8")
        assert drafted[f"{field}_digest"] == sha(content)
        assert len(drafted[f"{field}_digest"]) == 64
    assert drafted["release_statement"] == json.loads(release.layer("strategy_release_statement"))
    assert drafted["artifact_ref"] == json.loads(release.layer("strategy_artifact_ref"))
    assert "release_bom" not in drafted
    assert base64.b64decode(found.attestation_bundle_base64) == release.layer("attestation_bundle")
    assert found.trading_scope == {"connector": "binance", "pairs": ["BTC-USDT"], "leverage": 1}


