"""Reading a signed release back from its package, as ARX needs it.

Every release here is generated by the test: the layers, the two manifests and
the publication receipt are built the way the strategy publisher builds them,
with real SHA-256 digests. A fake registry serves them by digest; nothing is
recorded from a real registry.
"""

